"""Record fixed parser grammars, generated outputs and generator license hashes."""
import hashlib
import json
import re
import sys
import tarfile
from pathlib import Path, PurePosixPath

if len(sys.argv) != 5:
    raise SystemExit('usage: verify-parser-lineage.py UPSTREAM_ROOT SOURCE_TAR SOURCE_PROOF OUTPUT')
root, archive, proof_file, output = map(Path, sys.argv[1:])
sha = lambda data: hashlib.sha256(data).hexdigest()
proof_bytes = proof_file.read_bytes()
proof = json.loads(proof_bytes)
if sha(archive.read_bytes()) != proof['sourceTarSha256']:
    raise SystemExit('archive mismatch')
commit = proof['sourceCommit']
parser = root / 'packages/parser'
config_data = (parser / 'langium-config.json').read_bytes()
config = json.loads(config_data)
if len(config['languages']) != 15 or config['out'] != 'src/language/generated':
    raise SystemExit('unexpected generator configuration')
cli_root = root / 'node_modules/langium-cli'
cli = json.loads((cli_root / 'package.json').read_bytes())
if cli['version'] != '4.4.0' or cli['license'] != 'MIT':
    raise SystemExit('unexpected generator')
pending = [item['grammar'] for item in config['languages']]
grammars = {}
with tarfile.open(archive, 'r:gz') as source_tar:
    members = {m.name: m for m in source_tar if m.isfile()}
    while pending:
        raw = pending.pop()
        relative = PurePosixPath(raw)
        if relative.is_absolute() or '..' in relative.parts or relative.suffix != '.langium':
            raise SystemExit('unsafe grammar path')
        key = str(relative)
        if key in grammars:
            continue
        local = (parser / key).read_bytes()
        member = f'mermaid-{commit}/packages/parser/{key}'
        if member not in members or source_tar.extractfile(members[member]).read() != local:
            raise SystemExit('grammar source mismatch')
        grammars[key] = sha(local)
        for ref in re.findall(r'^\s*import\s+["\']([^"\']+)["\']', local.decode('utf-8'), re.M):
            combined = Path(key).parent / (ref if ref.endswith('.langium') else ref + '.langium')
            normalized = Path(__import__('os').path.normpath(str(combined)))
            if normalized.is_absolute() or '..' in normalized.parts:
                raise SystemExit('grammar import escapes parser')
            pending.append(normalized.as_posix())
    config_member = f'mermaid-{commit}/packages/parser/langium-config.json'
    if source_tar.extractfile(members[config_member]).read() != config_data:
        raise SystemExit('generator configuration mismatch')
generated_proof = next(x for x in proof['workspaces'] if x['name'] == 'parser')['generated']
for item in generated_proof:
    data = (parser / item['path']).read_bytes()
    if sha(data) != item['sha256'] or b'generated by langium-cli 4.4.0' not in data[:400]:
        raise SystemExit('generated file mismatch')
license_data = (cli_root / 'LICENSE').read_bytes()
evidence = {'sourceCommit': commit, 'sourceProofSha256': sha(proof_bytes), 'configurationSha256': sha(config_data),
            'grammarEntries': len(config['languages']), 'grammars': [{'path': k, 'sha256': v} for k, v in sorted(grammars.items())],
            'generator': {'name': 'langium-cli', 'version': cli['version'], 'license': cli['license'], 'licenseSha256': sha(license_data)},
            'outputs': generated_proof, 'limitations': 'Identifies local reproducible generated inputs, not license coverage or release-time generator dependency graph.'}
with output.open('x', encoding='utf-8', newline='\n') as stream:
    json.dump(evidence, stream, indent=2, ensure_ascii=False)
    stream.write('\n')
print(json.dumps({'configuredGrammars': len(config['languages']), 'grammarFiles': len(grammars), 'generator': cli['version'], 'generatedOutputs': len(generated_proof)}))
