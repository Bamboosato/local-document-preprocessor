import {build} from 'vite';
import {copyFile,mkdir,readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {writeSw} from './write-sw.mjs';
const root=fileURLToPath(new URL('.',import.meta.url));
const out=process.argv.find(x=>x.startsWith('--out='))?.slice(6)||'dist';
const generation=process.argv.find(x=>x.startsWith('--generation='))?.slice(13)||'default';
const materialRoot=process.argv.find(x=>x.startsWith('--materials='))?.slice(12);
const tiny=materialRoot?path.resolve(root,materialRoot,'tiny/mermaid.tiny.js'):root+'node_modules/@mermaid-js/tiny/dist/mermaid.tiny.js';
const inventory=JSON.parse(await readFile(new URL('../../docs/evidence/mermaid-tiny-license-inventory.json',import.meta.url)));
if(createHash('sha256').update(await readFile(tiny)).digest('hex')!==inventory.bundleSha256)throw Error('Tiny runtime hash mismatch');
if(!/^dist(?:-[ab])?$/.test(out)||! /^(?:default|A|B)$/.test(generation))throw Error('unsupported isolated build');
await build({root,configFile:false,publicDir:false,define:{__POC_VERSION__:JSON.stringify(generation)},plugins:[{name:'poc-generation',transformIndexHtml:html=>html.replace('<title>',`<meta name="poc-generation" content="${generation}"><title>`)}],build:{outDir:out,emptyOutDir:true,target:'es2022'}});
await mkdir(root+out,{recursive:true});
await copyFile(tiny,root+out+'/tiny.js');
await writeFile(root+out+'/worker.js',(await readFile(root+'worker.js','utf8'))+'\n// isolated PoC generation '+generation+'\n');
await writeSw(root+out);
